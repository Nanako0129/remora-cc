import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
import path from "node:path";
const base=process.argv[2];
const { reduceSession }=await import(pathToFileURL(path.join(base,"src/reducer.js")));
const { Session }=await import(pathToFileURL(path.join(base,"src/session.js")));
const s=new Session();s.startAssistant("a");const before=s.state;const old=before.messages[0];
s.finishAssistant("a",{inputTokens:4,outputTokens:2});
assert.deepEqual(s.committedUsage(),{inputTokens:4,outputTokens:2});
assert.equal(old.committed,false);assert.notEqual(s.state,before);
s.startAssistant("b");assert.deepEqual(s.committedUsage(),{inputTokens:4,outputTokens:2});
s.finishAssistant("b",{inputTokens:7,outputTokens:3});
assert.deepEqual(s.committedUsage(),{inputTokens:7,outputTokens:3});
assert.deepEqual(s.state.messages[0].usage,{inputTokens:4,outputTokens:2});
s.canonicalMessages.get("b").usage.inputTokens=999;
assert.equal(s.state.messages[1].usage.inputTokens,7);
assert.equal(reduceSession(s.state,{type:"unrelated"}),s.state);
assert.equal(reduceSession(s.state,{type:"message_delta",messageId:"missing",message:{id:"missing",committed:true,usage:{inputTokens:1,outputTokens:1}}}),s.state);
console.log("Acceptance checks passed");
